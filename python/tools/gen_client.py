def _runtime_modules() -> types.SimpleNamespace:
    """
    The client's standard-library modules this generator shares with the runtime.

    ``databay`` is registered as a bare namespace first, so its ``__init__`` (which imports
    generated modules that may not exist yet) never runs here.
    """
    package = types.ModuleType("databay")
    package.__path__ = [str(PACKAGE)]
    sys.modules.setdefault("databay", package)
    from databay import (
        error_catalog,
        operation,
        reference,
    )
    from databay.cli import flags, handwritten

    return types.SimpleNamespace(
        operation=operation, error_catalog=error_catalog, reference=reference, flags=flags, handwritten=handwritten
    )



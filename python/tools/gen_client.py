def python_schema_names(document: dict[str, Any]) -> dict[str, Any]:
    """
    ``document`` with each component schema named as a Python class: ``AnyOf-Output`` becomes ``AnyOfOutput``.

    The server names the request and response forms of one model ``<Model>-Input`` and ``<Model>-Output``.
    A name that still is not a class name, or that another schema already has, is an error.
    """
    schemas = document.get("components", {}).get("schemas", {})
    renames = {name: pascal(name) for name in schemas if not name.isidentifier()}
    if not renames:
        return document
    taken = set(schemas) - set(renames)
    for old, new in renames.items():
        if not new.isidentifier() or keyword.iskeyword(new) or new in taken:
            raise SpecError(f"{old}: this schema name cannot become the class name {new!r}")
        taken.add(new)
    prefix = "#/components/schemas/"

    def rename(node: object) -> object:
        if isinstance(node, dict):
            return {key: rename(value) for key, value in node.items()}
        if isinstance(node, list):
            return [rename(value) for value in node]
        if isinstance(node, str) and node.startswith(prefix) and node.removeprefix(prefix) in renames:
            return prefix + renames[node.removeprefix(prefix)]
        return node

    renamed: dict[str, Any] = {key: rename(value) for key, value in document.items()}
    renamed["components"]["schemas"] = {
        renames.get(name, name): schema for name, schema in renamed["components"]["schemas"].items()
    }
    return renamed


def generate(spec_path: Path, registry_path: Path, released_spec: Path = RELEASED_SPEC) -> dict[Path, str]:
    """Every generated file's path and text."""
    spec = Spec(python_schema_names(json.loads(spec_path.read_text(encoding="utf-8"))))
    version = api_version_in(API_VERSION_FILE)
    since = since_by_operation(spec.document, load_released(released_spec), version)
    collected, plan = collect(spec, since)
    server_codes, pipe_codes = load_registry(registry_path)
    by_noun: dict[str, list[Any]] = {}
    for op in collected.operations:
        by_noun.setdefault(op.noun, []).append(op)
    for ops in by_noun.values():
        ops.sort(key=lambda o: o.verb)
    files: dict[Path, str] = {}
    modules: dict[str, list[str]] = {}
    for name in sorted(spec.schemas):
        if name in plan.home:
            modules.setdefault(plan.home[name], []).append(name)
    for module in sorted(set(modules) | set(plan.aliases)):
        doc = "Models used by more than one noun." if module == "shared" else f"Models of the ``{module}`` noun."
        names = order_schemas(spec, modules.get(module, []))
        files[PACKAGE / "models" / f"{module}.py"] = render_model_module(spec, plan, module, names, doc)
    cli_nouns: dict[str, list[str]] = {}
    for noun, ops in sorted(by_noun.items()):
        module = module_name(noun)
        files[PACKAGE / "operations" / f"{module}.py"] = render_operations(noun, ops)
        files[PACKAGE / "resources" / f"{module}.py"] = render_resource(noun, ops, plan.home)
        commands = [op for op in ops if op.operation_id not in collected.curated]
        if commands:
            cli_nouns[noun] = [op.verb for op in commands]
            files[PACKAGE / "cli" / "commands" / f"{module}.py"] = render_cli(noun, commands)
    for package in ("models", "operations", "resources", "cli/commands"):
        files[PACKAGE / package / "__init__.py"] = ""
    files[PACKAGE / "api.py"] = render_api(sorted(by_noun))
    files[PACKAGE / "spec.py"] = render_spec(version, cli_nouns, collected.operations)
    files[PACKAGE / "error_codes.py"] = render_error_codes(server_codes)
    files[PACKAGE / "version.py"] = render_version(PYPROJECT)
    references = PACKAGE / "skill" / "references"
    files[references / "commands.md"] = RT.reference.commands_markdown(
        collected.operations, collected.curated, RT.handwritten.HANDWRITTEN
    )
    files[references / "errors.md"] = RT.reference.errors_markdown(server_codes, pipe_codes)
    return files


def order_schemas(spec: Spec, names: list[str]) -> list[str]:
    """Enums first, then models with the ones they use before them where the graph allows."""
    enums = [n for n in names if "enum" in spec.schemas[n]]
    models = [n for n in names if "enum" not in spec.schemas[n]]
    ordered: list[str] = []
    placed: set[str] = set()
    visiting: set[str] = set()

    def visit(name: str) -> None:
        if name in placed or name in visiting or name not in models:
            return
        visiting.add(name)
        for dependency in sorted(spec.refs(spec.schemas[name])):
            visit(dependency)
        visiting.discard(name)
        placed.add(name)
        ordered.append(name)

    for name in models:
        visit(name)
    return enums + ordered


def generated_paths() -> set[Path]:
    """The files a previous run wrote: every file in the generated packages, plus the fixed ones."""
    found: set[Path] = set()
    for package in ("models", "operations", "resources", "cli/commands"):
        directory = PACKAGE / package
        if directory.exists():
            found |= set(directory.glob("*.py"))
    fixed_files = (
        "api.py",
        "spec.py",
        "error_codes.py",
        "version.py",
        "skill/references/commands.md",
        "skill/references/errors.md",
    )
    for fixed in fixed_files:
        if (PACKAGE / fixed).exists():
            found.add(PACKAGE / fixed)
    return found


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="list files that differ from a fresh run; write nothing")
    parser.add_argument("--spec", type=Path, default=SPEC)
    parser.add_argument("--error-codes", type=Path, default=ERROR_CODES)
    parser.add_argument("--released-spec", type=Path, default=RELEASED_SPEC)
    args = parser.parse_args()
    try:
        files = generate(args.spec, args.error_codes, args.released_spec)
    except (SpecError, ContractError) as exc:
        raise SystemExit(f"gen_client: {exc}") from exc
    stale = generated_paths() - set(files)
    if args.check:
        differ = sorted(
            str(p.relative_to(REPO_ROOT))
            for p, text in files.items()
            if not p.exists() or p.read_text(encoding="utf-8") != text
        )
        differ += sorted(f"{p.relative_to(REPO_ROOT)} (no longer generated)" for p in stale)
        if differ:
            print("generated files differ from python/tools/gen_client.py's output:\n  " + "\n  ".join(differ))
            raise SystemExit(1)
        print(f"gen_client: {len(files)} files match")
        return
    for path in stale:
        path.unlink()
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
    print(f"gen_client: wrote {len(files)} files")


if __name__ == "__main__":
    main()

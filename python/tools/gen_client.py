def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^0-9A-Za-z]+", name) if part)


def module_name(noun: str) -> str:
    name = noun.replace("-", "_")
    return f"{name}_" if keyword.iskeyword(name) or name == "shared" else name


def constant_name(op_id: str) -> str:
    return re.sub(r"[^0-9A-Za-z]+", "_", op_id).upper()


@dataclass
class Spec:
    document: dict[str, Any]

    @property
    def schemas(self) -> dict[str, Any]:
        return self.document["components"]["schemas"]

    def ref_name(self, schema: dict[str, Any]) -> str | None:
        ref = schema.get("$ref")
        return ref.rsplit("/", 1)[1] if isinstance(ref, str) else None

    def resolve(self, schema: dict[str, Any]) -> dict[str, Any]:
        seen = 0
        while "$ref" in schema:
            schema = self.schemas[self.ref_name(schema)]
            seen += 1
            if seen > 50:  # noqa: PLR2004
                raise SpecError("a $ref chain does not end")
        return schema

    def refs(self, node: Any) -> set[str]:  # noqa: ANN401
        if isinstance(node, dict):
            found = {self.ref_name(node)} if "$ref" in node else set()
            return found.union(*(self.refs(v) for v in node.values()))
        if isinstance(node, list):
            return set().union(*(self.refs(v) for v in node))
        return set()

    def closure(self, names: set[str]) -> set[str]:
        seen: set[str] = set()
        pending = set(names)
        while pending:
            name = pending.pop()
            if name in seen:
                continue
            seen.add(name)
            pending |= self.refs(self.schemas[name]) - seen
        return seen


def non_null(options: list[dict[str, Any]]) -> list[dict[str, Any]]:
    return [o for o in options if o.get("type") != "null"]


def map_values(schema: dict[str, Any]) -> dict[str, Any] | None:
    """The schema of a map's values: ``additionalProperties``, or the one ``patternProperties`` of a constrained key."""
    extra = schema.get("additionalProperties")
    if isinstance(extra, dict) and extra:
        return extra
    patterns = list(schema.get("patternProperties", {}).values())
    if len(patterns) > 1:
        raise SpecError(f"a map with {len(patterns)} key patterns is not handled")
    return patterns[0] if patterns else None


def is_secret(spec: Spec, schema: dict[str, Any], seen: frozenset[str] = frozenset()) -> bool:
    """
    Whether a value is or holds a secret: ``format: password`` on it or on anything inside it.

    A JSON field that holds a secret (canvas activate's ``secrets``) is read like a secret as a whole,
    so the secret never reaches a value flag or a verbose log.
    """
    name = spec.ref_name(schema)
    if name is not None:
        return name not in seen and is_secret(spec, spec.schemas[name], seen | {name})
    if schema.get("format") == "password":
        return True
    nested = [*schema.get("anyOf", []), *schema.get("oneOf", []), *schema.get("properties", {}).values()]
    if isinstance(schema.get("items"), dict):
        nested.append(schema["items"])
    values = map_values(schema)
    if values is not None:
        nested.append(values)
    return any(is_secret(spec, option, seen) for option in nested)


def value_kind(spec: Spec, schema: dict[str, Any], where: str) -> tuple[str, tuple[str, ...], str | None]:
    """``(kind, choices, item kind)`` of a parameter or field, as the CLI reads it."""
    schema = spec.resolve(schema)
    options = non_null(schema.get("anyOf", []))
    if "anyOf" in schema:
        if len(options) == 1:
            return value_kind(spec, options[0], where)
        return "json", (), None
    if "oneOf" in schema:
        return "json", (), None
    kind = schema.get("type")
    if isinstance(kind, list):
        rest = [k for k in kind if k != "null"]
        if len(rest) != 1:
            return "json", (), None
        kind = rest[0]
    choices = tuple(str(v) for v in schema.get("enum", ()))
    if "const" in schema:
        choices = (str(schema["const"]),)
    if kind in {"string", "integer", "number", "boolean"}:
        return kind, choices, None
    if kind == "array":
        item, item_choices, _ = value_kind(spec, schema.get("items", {}), where)
        if item in {"string", "integer", "number"}:
            return "list", item_choices, item
        return "json", (), None
    if kind == "object" or kind is None:
        return "json", (), None
    raise SpecError(f"{where}: schema type {kind!r} is not handled")


def description(schema: dict[str, Any]) -> str:
    return str(schema.get("description") or schema.get("title") or "")


def make_param(spec: Spec, name: str, location: str, schema: dict[str, Any], required: bool, where: str) -> Any:  # noqa: ANN401
    kind, choices, item_kind = value_kind(spec, schema, f"{where} {name}")
    return Param(
        name=name,
        location=location,
        kind=kind,
        required=required,
        description=description(schema),
        secret=is_secret(spec, schema),
        choices=choices,
        item_kind=item_kind,
        nullable=any(o.get("type") == "null" for o in spec.resolve(schema).get("anyOf", [])),
    )


def settable(spec: Spec, schema: dict[str, Any]) -> bool:
    """Whether a body property can carry a value: one whose only type is ``null`` cannot, so it is no option."""
    return spec.resolve(schema).get("type") != "null"


def body_of(spec: Spec, op: dict[str, Any], where: str) -> Any:  # noqa: ANN401
    request = op.get("requestBody")
    if request is None:
        return None
    content = request.get("content", {})
    if set(content) != {"application/json"}:
        raise SpecError(f"{where}: request body content {sorted(content)} is not handled")
    raw = content["application/json"]["schema"]
    schema_name = spec.ref_name(raw)
    schema = spec.resolve(raw)
    if "discriminator" in schema:
        discriminator, variants = variants_of(spec, schema, where)
        return RT.operation.Body(schema=schema_name, discriminator=discriminator, variants=variants)
    if schema.get("type") != "object":
        raise SpecError(f"{where}: a request body of type {schema.get('type')!r} is not handled")
    required = set(schema.get("required", []))
    properties = schema.get("properties", {})
    held = [name for name, prop in properties.items() if "discriminator" in spec.resolve(prop)]
    if len(held) > 1:
        raise SpecError(f"{where}: a body with two discriminated properties {held} is not handled")
    if held and held[0] not in required:
        raise SpecError(f"{where}: an optional discriminated property {held[0]} is not handled")
    params = tuple(
        make_param(spec, name, "body", prop, name in required, where)
        for name, prop in properties.items()
        if name not in held and settable(spec, prop)
    )
    if not held:
        return RT.operation.Body(schema=schema_name, fields=params)
    discriminator, variants = variants_of(spec, spec.resolve(properties[held[0]]), where)
    return RT.operation.Body(
        schema=schema_name, fields=params, discriminator=discriminator, variants=variants, variant_field=held[0]
    )


def variants_of(spec: Spec, schema: dict[str, Any], where: str) -> tuple[str, tuple[Any, ...]]:
    """A discriminated schema's discriminator and ``(key, schema name, fields)`` per mapping key."""
    discriminator = schema["discriminator"]["propertyName"]
    variants = []
    for key, ref in sorted(schema["discriminator"]["mapping"].items()):
        variant_name = ref.rsplit("/", 1)[1]
        variant = spec.schemas[variant_name]
        required = set(variant.get("required", []))
        params = tuple(
            make_param(spec, name, "body", prop, name in required, where)
            for name, prop in variant.get("properties", {}).items()
            if name != discriminator and settable(spec, prop)
        )
        variants.append((key, variant_name, params))
    return discriminator, tuple(variants)


def wait_of(raw: dict[str, Any] | None) -> Any:  # noqa: ANN401
    if not raw:
        return None
    conditional = tuple(
        (
            value,
            RT.operation.Condition(
                field=cond["field"],
                pending=tuple(cond.get("pending", [])),
                success=tuple(cond.get("success", [])),
                failure=tuple(cond.get("failure", [])),
            ),
        )
        for value, cond in sorted(raw.get("conditional", {}).items())
    )
    return RT.operation.Wait(
        status_operation=raw["status_operation"],
        bind=tuple(sorted(raw["bind"].items())),
        field=raw["field"],
        pending=tuple(raw["pending"]),
        success=tuple(raw["success"]),
        failure=tuple(raw["failure"]),
        error_field=raw.get("error_field"),
        conditional=conditional,
        timeout_s=raw.get("timeout_s"),
    )


def verdict_of(raw: dict[str, Any] | None) -> Any:  # noqa: ANN401
    if not raw:
        return None
    return RT.operation.Verdict(field=raw["field"], ok=tuple(raw["ok"]), not_ready=tuple(raw["not_ready"]))


@dataclass
class ModelPlan:
    """Which module each schema's class lives in, and the extra classes and aliases to emit."""

    home: dict[str, str] = field(default_factory=dict)
    request_only: set[str] = field(default_factory=set)
    #: module -> [(class name, enum values)] for enums declared inline on a property.
    inline_enums: dict[str, list[tuple[str, tuple[str, ...]]]] = field(default_factory=dict)
    #: module -> [(alias name, type expression)] for answers that are not one schema.
    aliases: dict[str, list[tuple[str, str]]] = field(default_factory=dict)


class TypeWriter:
    """Writes the Python type of a schema inside one model module, recording what it needs to import."""

    def __init__(self, spec: Spec, plan: ModelPlan, module: str) -> None:
        self.spec = spec
        self.plan = plan
        self.module = module
        self.imports: dict[str, set[str]] = {}
        self.typing: set[str] = set()

    def ref(self, name: str) -> str:
        home = self.plan.home[name]
        if home != self.module:
            self.imports.setdefault(home, set()).add(name)
        return name

    def type_of(self, schema: dict[str, Any], owner: str, prop: str) -> str:
        name = self.spec.ref_name(schema)
        if name is not None:
            return self.ref(name)
        if "anyOf" in schema:
            parts: list[str] = []
            for option in schema["anyOf"]:
                text = self.type_of(option, owner, prop)
                if text not in parts:
                    parts.append(text)
            return " | ".join(parts)
        if "oneOf" in schema:
            options = [self.type_of(option, owner, prop) for option in schema["oneOf"]]
            union = " | ".join(options)
            discriminator = schema.get("discriminator", {}).get("propertyName")
            if discriminator is None:
                return union
            self.typing.add("Annotated")
            self.imports.setdefault("pydantic", set()).add("Field")
            return f"Annotated[{union}, Field(discriminator={discriminator!r})]"
        if "const" in schema:
            self.typing.add("Literal")
            return f"Literal[{schema['const']!r}]"
        if "enum" in schema:
            return self.inline_enum(schema, owner, prop)
        kind = schema.get("type")
        if isinstance(kind, list):
            return " | ".join(self.type_of({**schema, "type": k}, owner, prop) for k in kind)
        return self.scalar(schema, kind, owner, prop)

    def scalar(self, schema: dict[str, Any], kind: str | None, owner: str, prop: str) -> str:
        if kind == "string":
            fmt = schema.get("format")
            if fmt == "date-time":
                self.imports.setdefault("datetime", set()).add("datetime")
                return "datetime"
            if fmt == "date":
                self.imports.setdefault("datetime", set()).add("date")
                return "date"
            return "str"
        simple = {"integer": "int", "number": "float", "boolean": "bool", "null": "None"}
        if kind in simple:
            return simple[kind]
        if kind == "array":
            items = schema.get("items")
            if not items:
                self.typing.add("Any")
                return "list[Any]"
            return f"list[{self.type_of(items, owner, prop)}]"
        if kind == "object" or kind is None:
            if schema.get("properties"):
                raise SpecError(f"{owner}.{prop}: an inline object with properties is not handled")
            values = map_values(schema)
            if values is not None:
                return f"dict[str, {self.type_of(values, owner, prop)}]"
            self.typing.add("Any")
            return "dict[str, Any]" if kind == "object" else "Any"
        raise SpecError(f"{owner}.{prop}: type {kind!r} is not handled")

    def inline_enum(self, schema: dict[str, Any], owner: str, prop: str) -> str:
        values = tuple(str(v) for v in schema["enum"])
        if any(not isinstance(v, str) for v in schema["enum"]):
            raise SpecError(f"{owner}.{prop}: a non-string enum is not handled")
        name = f"{owner}{pascal(prop)}"
        known = dict(self.plan.inline_enums.setdefault(self.module, []))
        if name in known and known[name] != values:
            raise SpecError(f"{name}: two inline enums would share this class name")
        if name not in known:
            self.plan.inline_enums[self.module].append((name, values))
        return name


def member_name(value: str, enum: str) -> str:
    name = re.sub(r"[^0-9A-Za-z]+", "_", value).strip("_").upper() or "EMPTY"
    if name[0].isdigit():
        name = f"V_{name}"
    if name.startswith("_"):
        raise SpecError(f"{enum}: value {value!r} has no member name")
    return name


def render_enum(name: str, values: tuple[str, ...]) -> list[str]:
    lines = [f"class {name}(OpenStrEnum):"]
    seen: set[str] = set()
    for value in values:
        member = member_name(value, name)
        if member in seen:
            raise SpecError(f"{name}: two values map to member {member}")
        seen.add(member)
        lines.append(f"    {member} = {value!r}")
    if not values:
        lines.append("    pass")
    return [*lines, "", ""]


def field_name(prop: str) -> tuple[str, bool]:
    """A property's Python field name, and whether it needs an alias."""
    name = re.sub(r"[^0-9A-Za-z_]+", "_", prop)
    if not name or name[0].isdigit():
        name = f"f_{name}"
    if keyword.iskeyword(name) or name in BASEMODEL_NAMES or name.startswith(("model_", "_")):
        name = f"{name.lstrip('_')}_"
    return name, name != prop


def render_model(writer: TypeWriter, name: str, schema: dict[str, Any], base: str) -> list[str]:
    if schema.get("type") != "object" or "properties" not in schema:
        raise SpecError(f"{name}: a component schema that is not an object with properties is not handled")
    required = set(schema.get("required", []))
    body: list[str] = []
    for prop, prop_schema in schema["properties"].items():
        text = writer.type_of(prop_schema, name, prop)
        ident, aliased = field_name(prop)
        if prop in required:
            annotation, default = text, None
        elif "default" in prop_schema:
            annotation, default = text, repr(prop_schema["default"])
        else:
            annotation = text if "None" in text.split(" | ") else f"{text} | None"
            default = "None"
        if aliased:
            writer.imports.setdefault("pydantic", set()).add("Field")
            args = ([f"default={default}"] if default is not None else []) + [f"alias={prop!r}"]
            body.append(f"    {ident}: {annotation} = Field({', '.join(args)})")
        elif default is not None:
            body.append(f"    {ident}: {annotation} = {default}")
        else:
            body.append(f"    {ident}: {annotation}")
    return [f"class {name}({base}):", *body, "", ""]


def render_model_module(spec: Spec, plan: ModelPlan, module: str, names: list[str], doc: str) -> str:
    writer = TypeWriter(spec, plan, module)
    blocks: list[str] = []
    enums: list[str] = []
    bases: set[str] = set()
    for name in names:
        schema = spec.schemas[name]
        if "enum" in schema:
            if schema.get("type") != "string":
                raise SpecError(f"{name}: a non-string enum is not handled")
            enums += render_enum(name, tuple(schema["enum"]))
            continue
        base = "RequestModel" if name in plan.request_only else "ResponseModel"
        bases.add(base)
        blocks += render_model(writer, name, schema, base)
    for alias, expression in plan.aliases.get(module, []):
        rendered = expression.format_map(_AliasRefs(writer))
        blocks += [f"{alias} = {rendered}", "", ""]
    for name, values in plan.inline_enums.get(module, []):
        if name in spec.schemas:
            raise SpecError(f"{name}: an inline enum's class name is also a component schema")
        enums += render_enum(name, values)
    if enums:
        bases.add("OpenStrEnum")
    groups: list[list[str]] = []
    stdlib = []
    if "datetime" in writer.imports:
        stdlib.append(f"from datetime import {', '.join(sorted(writer.imports.pop('datetime')))}")
    if writer.typing:
        stdlib.append(f"from typing import {', '.join(sorted(writer.typing))}")
    if stdlib:
        groups.append(stdlib)
    if "pydantic" in writer.imports:
        groups.append([f"from pydantic import {', '.join(sorted(writer.imports.pop('pydantic')))}"])
    first_party = [f"from databay.model_base import {', '.join(sorted(bases))}"] if bases else []
    first_party += [
        f"from databay.models.{other} import {', '.join(sorted(writer.imports[other]))}"
        for other in sorted(writer.imports)
    ]
    if first_party:
        groups.append(first_party)
    head = HEADER.format(doc=doc) + "\nfrom __future__ import annotations\n\n"
    head += "\n\n".join("\n".join(group) for group in groups)
    return head + "\n\n\n" + "\n".join(enums + blocks).rstrip("\n") + "\n"


class _AliasRefs(dict):
    """Fills ``{Schema}`` placeholders in an alias expression through the writer, recording imports."""

    def __init__(self, writer: TypeWriter) -> None:
        super().__init__()
        self.writer = writer

    def __missing__(self, key: str) -> str:
        return self.writer.ref(key)



def with_rows(spec: Spec, op: dict[str, Any], response: Any, columns: list[str], where: str) -> Any:  # noqa: ANN401
    """
    ``response`` with ``rows`` set when the declared columns name the items of a list the answer object holds.

    The columns must fit the answer's items (an array answer), the answer itself, or exactly one
    array-of-objects field of it; anything else is an error naming the operation.
    """
    from dataclasses import replace

    if not columns or response.kind != "json" or response.shape != "object":
        return response
    status = next(s for s in SUCCESS if s in op["responses"])
    schema = spec.resolve(op["responses"][status]["content"]["application/json"]["schema"])
    properties = schema.get("properties", {})
    if set(columns) <= set(properties):
        return response
    holders = []
    for name, raw in properties.items():
        prop = spec.resolve(raw)
        items = spec.resolve(prop.get("items", {})) if prop.get("type") == "array" else {}
        if set(columns) <= set(items.get("properties", {})):
            holders.append(name)
    if len(holders) != 1:
        raise SpecError(
            f"{where}: columns {columns} fit {holders or 'no'} list in the answer; exactly one must hold them"
        )
    if holders[0] not in schema.get("required", []):
        # Required, so every validated answer has the list a table or CSV prints.
        raise SpecError(f"{where}: the list {holders[0]} that holds the columns must be required")
    return replace(response, rows=f"/{holders[0]}")


def response_of(spec: Spec, op: dict[str, Any], noun: str, op_id: str, plan: ModelPlan, where: str) -> Any:  # noqa: ANN401
    status = next((s for s in SUCCESS if s in op.get("responses", {})), None)
    if status is None:
        raise SpecError(f"{where}: no 2xx response")
    content = op["responses"][status].get("content") or {}
    if status == "204" or not content:
        return RT.operation.Response(kind="empty")
    if "application/json" not in content:
        return RT.operation.Response(kind="text")
    schema = content["application/json"].get("schema") or {}
    name = spec.ref_name(schema)
    module = module_name(noun)
    if name is not None:
        resolved = spec.resolve(schema)
        shape = "array" if resolved.get("type") == "array" else "object"
        return RT.operation.Response(kind="json", model=f"{plan.home[name]}:{name}", shape=shape)
    if not schema:
        return RT.operation.Response(kind="json")
    alias = f"{pascal(op_id)}Response"
    plan.aliases.setdefault(module, []).append((alias, _alias_expression(spec, schema)))
    shape = "array" if schema.get("type") == "array" else "any"
    return RT.operation.Response(kind="json", model=f"{module}:{alias}", shape=shape)


def _alias_expression(spec: Spec, schema: dict[str, Any]) -> str:
    """A type expression with ``{Schema}`` placeholders, for an answer that is not one component schema."""
    name = spec.ref_name(schema)
    if name is not None:
        return "{" + name + "}"
    if "anyOf" in schema:
        return " | ".join(_alias_expression(spec, o) for o in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"list[{_alias_expression(spec, schema.get('items') or {})}]"
    simple = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "null": "None"}
    if kind in simple:
        return simple[kind]
    if kind == "object":
        values = map_values(schema)
        if values is not None:
            return f"dict[str, {_alias_expression(spec, values)}]"
        return "dict[str, object]"
    raise SpecError(f"an answer schema {json.dumps(schema)[:80]} is not handled")


def collect(spec: Spec, since: dict[str, str]) -> tuple[Collected, ModelPlan]:
    plan = ModelPlan()
    raw_ops: list[tuple[str, str, dict[str, Any]]] = []
    for path, methods in sorted(spec.document["paths"].items()):
        for method, op in sorted(methods.items()):
            raw_ops.append((path, method, op))
    reached: dict[str, set[str]] = {}
    request_schemas: set[str] = set()
    response_schemas: set[str] = set()
    for _path, _method, op in raw_ops:
        declared = op[EXTENSION]
        noun = declared["noun"]
        request = spec.closure(spec.refs(op.get("requestBody", {})))
        response = spec.closure(spec.refs({k: v for k, v in op.get("responses", {}).items() if k in SUCCESS}))
        request_schemas |= request
        response_schemas |= response
        reached.setdefault(noun, set()).update(request | response)
    users: dict[str, set[str]] = {}
    for noun, names in reached.items():
        for name in names:
            users.setdefault(name, set()).add(noun)
    for name, nouns in users.items():
        plan.home[name] = module_name(next(iter(nouns))) if len(nouns) == 1 else "shared"
    plan.request_only = request_schemas - response_schemas

    operations: list[Any] = []
    curated: dict[str, str] = {}
    for path, method, op in raw_ops:
        declared = op[EXTENSION]
        op_id = op["operationId"]
        where = f"{method.upper()} {path}"
        noun = declared["noun"]
        shape = declared["agent_shape"]
        if shape.startswith("curated:"):
            curated[op_id] = shape.removeprefix("curated:")
        elif shape != "direct":
            raise SpecError(f"{where}: agent_shape {shape!r} is not handled")
        params = []
        for raw in op.get("parameters", []):
            location = raw["in"]
            if location == "header" and raw["name"].lower() in {IDEMPOTENCY_HEADER, PROJECT_HEADER}:
                continue
            if location not in {"path", "query", "header"}:
                raise SpecError(f"{where}: a parameter in {location} is not handled")
            params.append(
                make_param(spec, raw["name"], location, raw.get("schema", {}), bool(raw.get("required")), where)
            )
        operations.append(
            Operation(
                operation_id=op_id,
                noun=noun,
                verb=declared["verb"],
                method=method,
                path=path,
                summary=str(op.get("summary", "")),
                description=str(op.get("description", "")),
                project=declared.get("project"),
                destructive=bool(declared["destructive"]),
                idempotent=bool(declared["idempotent"]),
                since=since[f"{method.upper()} {path}"],
                params=tuple(params),
                body=body_of(spec, op, where),
                response=with_rows(
                    spec, op, response_of(spec, op, noun, op_id, plan, where), declared.get("columns", []), where
                ),
                examples=tuple(declared["examples"]),
                columns=tuple(declared.get("columns", [])),
                wait=wait_of(declared.get("wait")),
                verdict=verdict_of(declared.get("verdict")),
            )
        )
    operations = attach_resumes(operations)
    check_flags(operations)
    return Collected(operations, curated, reached, request_schemas, response_schemas), plan


def attach_resumes(operations: list[Any]) -> list[Any]:
    """Give each status operation a wait polls the wait it can resume; two different waits on one is an error."""
    from dataclasses import replace

    by_id = {op.operation_id: op for op in operations}
    resumes: dict[str, Any] = {}
    for op in operations:
        if op.wait is None:
            continue
        status_id = op.wait.status_operation
        if status_id not in by_id:
            raise SpecError(f"{op.operation_id}: its wait polls {status_id}, which is not exposed")
        own = replace(op.wait, bind=tuple((name, f"path:{name}") for name, _ in op.wait.bind))
        if status_id in resumes and resumes[status_id] != own:
            raise SpecError(f"{status_id}: two waits poll it with different rules")
        resumes[status_id] = own
    return [replace(op, resumes=resumes[op.operation_id]) if op.operation_id in resumes else op for op in operations]


def flag_words(param: Any) -> list[str]:  # noqa: ANN401
    """Every flag a field can take, without dashes: its own, how a secret is read, how a boolean is turned off."""
    if param.secret:
        return [param.flag, f"{param.flag}-env", f"{param.flag}-stdin"]
    return [param.flag, f"no-{param.flag}"] if param.kind == "boolean" else [param.flag]


def check_flags(operations: list[Any]) -> None:
    """Every command's flags are distinct, a body's beside its variant's included, and none is one the CLI reserves."""
    reserved = RT.flags.RESERVED_FLAGS
    for op in operations:
        variants = [None] if op.body is None or op.body.discriminator is None else [k for k, _, _ in op.body.variants]
        for variant in variants:
            fields_ = list(op.params) + list(op.body.fields_of(variant) if op.body else [])
            names = [word for p in fields_ for word in flag_words(p)]
            clash = sorted({n for n in names if names.count(n) > 1} | (set(names) & reserved))
            if clash:
                where = op.operation_id if variant is None else f"{op.operation_id} {variant}"
                raise SpecError(f"{where}: flags {clash} collide with each other or with the CLI's own")
            identifiers = [p.identifier for p in fields_]
            if len(set(identifiers)) != len(identifiers):
                raise SpecError(f"{op.operation_id}: two inputs share a Python name")
            secret_params = sorted(p.name for p in op.params if p.secret)
            if secret_params:
                # The CLI reads a secret into the JSON body only; a secret parameter would go astray.
                raise SpecError(f"{op.operation_id}: parameters {secret_params} are secret; only body fields may be")


def render_value(value: Any, indent: int = 0) -> str:  # noqa: ANN401
    """Python source for a runtime dataclass value, leaving out fields at their defaults."""
    pad = " " * indent
    inner = " " * (indent + 4)
    if is_dataclass(value):
        args = []
        for item in fields(value):
            current = getattr(value, item.name)
            if item.default is not item.default_factory and current == item.default:  # type: ignore[comparison-overlap]
                continue
            args.append(f"{inner}{item.name}={render_value(current, indent + 4)},")
        if not args:
            return f"{type(value).__name__}()"
        return f"{type(value).__name__}(\n" + "\n".join(args) + f"\n{pad})"
    if isinstance(value, tuple):
        if not value:
            return "()"
        items = [f"{inner}{render_value(item, indent + 4)}," for item in value]
        return "(\n" + "\n".join(items) + f"\n{pad})"
    return repr(value)


def render_operations(noun: str, ops: list[Any]) -> str:
    names = sorted({type(x).__name__ for op in ops for x in _dataclasses_in(op)})
    lines = [
        HEADER.format(doc=f"The ``{noun}`` operations."),
        f"from databay.operation import {', '.join(names)}",
        "",
    ]
    for op in ops:
        lines += ["", f"{constant_name(op.operation_id)} = {render_value(op)}"]
    lines += ["", "OPERATIONS = (", *[f"    {constant_name(op.operation_id)}," for op in ops], ")", ""]
    return "\n".join(lines)


def _dataclasses_in(value: Any) -> list[Any]:  # noqa: ANN401
    found = []
    if is_dataclass(value):
        found.append(value)
        for item in fields(value):
            found += _dataclasses_in(getattr(value, item.name))
    elif isinstance(value, tuple):
        for item in value:
            found += _dataclasses_in(item)
    return found


def py_type(param: Any, sdk_models: dict[str, str]) -> str:  # noqa: ANN401
    del sdk_models
    simple = {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}
    if param.secret:
        return "SecretStr | str" if param.kind != "json" else "dict[str, Any]"
    if param.kind in simple:
        return simple[param.kind]
    if param.kind == "list":
        return f"list[{simple[param.item_kind]}]"
    return "Any"


def _signature(op: Any, wait_mode: str | None) -> list[str]:  # noqa: ANN401
    location = op.project_location
    parts: list[str] = []
    inputs = list(op.params) + (list(op.body.fields) if op.body is not None else [])
    required = [p for p in inputs if p.required and not (location and location[1] == p.name)]
    optional = [p for p in inputs if p not in required]
    parts.extend(f"{param.identifier}: {py_type(param, {})}" for param in required)
    if op.body is not None and op.body.discriminator is not None:
        variants = " | ".join(schema for _, schema, _ in op.body.variants)
        parts.append(f"{_variant_argument(op)}: {variants} | dict[str, Any]")
    for param in optional:
        none = " | None" if param.nullable and param.location == "body" else ""
        parts.append(f"{param.identifier}: {py_type(param, {})}{none} | Unset = UNSET")
    if op.project is not None:
        parts.append("project: str | None = None")
    if op.idempotent:
        parts.append("idempotency_key: str | None = None")
    if wait_mode == "false":
        parts.append("wait: Literal[False] = False")
        parts.append("timeout: None = None")
    elif wait_mode == "true":
        parts.append("wait: Literal[True]")
        parts.append("timeout: float | None = None")
    elif wait_mode == "impl":
        parts.append("wait: bool = False")
        parts.append("timeout: float | None = None")
    return parts


def _variant_argument(op: Any) -> str:  # noqa: ANN401
    """The SDK argument that takes a variant model: the whole ``body``, or the property the variants belong to."""
    return RT.operation.python_identifier(op.body.variant_field or "body")


def _result_type(op: Any) -> str:  # noqa: ANN401
    if op.response.kind == "empty":
        return "None"
    if op.response.kind == "text":
        return "str"
    if op.response.model is None:
        return "Any"
    return op.response.model.partition(":")[2]


def render_resource(noun: str, ops: list[Any], homes: dict[str, str]) -> str:
    module = module_name(noun)
    model_imports: dict[str, set[str]] = {}
    for op in ops:
        if op.response.model:
            home, _, name = op.response.model.partition(":")
            model_imports.setdefault(home, set()).add(name)
        if op.body is not None and op.body.discriminator is not None:
            for _, schema, _ in op.body.variants:
                model_imports.setdefault(homes[schema], set()).add(schema)
    body = [f"class {pascal(noun)}Resource(Resource):"]
    for op in ops:
        body += _method(op)
    text = "\n".join(body)
    typing = sorted(n for n in ("Any", "Literal", "overload") if re.search(rf"\b{n}\b", text))
    runtime = sorted(n for n in ("UNSET", "Resource", "Unset", "Waited") if re.search(rf"\b{n}\b", text))
    lines = [
        HEADER.format(doc=f"``client.{module}``: the ``{noun}`` operations."),
        "from __future__ import annotations",
        "",
        f"from typing import {', '.join(['TYPE_CHECKING', *typing])}",
        "",
        f"from databay.operations import {module} as _ops",
        f"from databay.resource import {', '.join(runtime)}",
    ]
    checking = ["    from pydantic import SecretStr", ""] if re.search(r"\bSecretStr\b", text) else []
    checking += [
        f"    from databay.models.{home} import {', '.join(sorted(names))}"
        for home, names in sorted(model_imports.items())
    ]
    if checking:
        lines += ["", "if TYPE_CHECKING:", *checking]
    return "\n".join(lines).rstrip() + "\n\n\n" + text.rstrip() + "\n"


def _method(op: Any) -> list[str]:  # noqa: ANN401
    name = RT.operation.python_identifier(op.verb)
    result = _result_type(op)
    location = op.project_location
    inputs = list(op.params) + (list(op.body.fields) if op.body else [])
    args = [f"{param.name!r}: {param.identifier}" for param in inputs]
    call = [f"_ops.{constant_name(op.operation_id)}", "{" + ", ".join(args) + "}"]
    if op.project is not None:
        call.append("project=project")
    if op.idempotent:
        call.append("idempotency_key=idempotency_key")
    if op.body is not None and op.body.discriminator is not None:
        call.append(f"body={_variant_argument(op)}")
    doc = (op.summary or op.verb).strip().rstrip(".") + f". ``{op.command}``."
    del location

    def header(mode: str | None) -> list[str]:
        parts = _signature(op, mode)
        if not parts:
            return [f"    def {name}(self) -> "]
        return [f"    def {name}(", "        self,", "        *,", *[f"        {part}," for part in parts], "    ) -> "]

    out: list[str] = []
    if op.offers_wait:
        call += ["wait=wait", "timeout=timeout"]
        for mode, returns in (("false", result), ("true", f"Waited[{result}]")):
            lines = header(mode)
            lines[-1] += f"{returns}: ..."
            out += ["", "    @overload", *lines, ""]
        lines = header("impl")
        lines[-1] += f"{result} | Waited[{result}]:"
        out += lines
    else:
        lines = header(None)
        lines[-1] += f"{result}:"
        out += ["", *lines]
    out += [f'        """{doc}"""', f"        return self._call({', '.join(call)})"]
    return out


def render_api(nouns: list[str]) -> str:
    lines = [
        HEADER.format(doc="One attribute per noun on the SDK client; each imports its resource on first use."),
        "from __future__ import annotations",
        "",
        "from functools import cached_property",
        "from typing import TYPE_CHECKING",
        "",
        "if TYPE_CHECKING:",
        "    from databay.invoke import Session",
    ]
    lines.extend(f"    from databay.resources.{module_name(noun)} import {pascal(noun)}Resource" for noun in nouns)
    lines += [
        "",
        "",
        "class Api:",
        "    def __init__(self, session: Session) -> None:",
        "        self._session = session",
    ]
    for noun in nouns:
        module = module_name(noun)
        lines += [
            "",
            "    @cached_property",
            f"    def {module}(self) -> {pascal(noun)}Resource:",
            f"        from databay.resources.{module} import {pascal(noun)}Resource",
            "",
            f"        return {pascal(noun)}Resource(self._session)",
        ]
    return "\n".join(lines) + "\n"


def render_cli(noun: str, ops: list[Any]) -> str:
    module = module_name(noun)
    return "\n".join(
        [
            HEADER.format(doc=f"``databay {noun}``: imported only when that noun runs."),
            "from databay.cli.build import noun_group",
            f"from databay.operations import {module} as _ops",
            "",
            "group = noun_group(",
            f"    {noun!r},",
            "    (",
            *[f"        _ops.{constant_name(op.operation_id)}," for op in ops],
            "    ),",
            ")",
            "",
        ]
    )


def render_spec(version: str, cli_nouns: dict[str, list[str]], operations: list[Any]) -> str:
    lines = [
        HEADER.format(doc="The API version this client speaks, and where each noun and operation is generated."),
        f"API_VERSION = {version!r}",
        "",
        "#: CLI noun -> (its module under ``databay.cli.commands``, the verbs it has).",
        "NOUNS: dict[str, tuple[str, tuple[str, ...]]] = {",
    ]
    lines.extend(
        f"    {noun!r}: ({module_name(noun)!r}, {tuple(sorted(cli_nouns[noun]))!r})," for noun in sorted(cli_nouns)
    )
    lines += ["}", "", "#: Operation id -> (its module under ``databay.operations``, its constant).", "OPERATIONS = {"]
    for op in sorted(operations, key=lambda o: o.operation_id):
        lines.append(f"    {op.operation_id!r}: ({module_name(op.noun)!r}, {constant_name(op.operation_id)!r}),")
    lines += ["}", ""]
    return "\n".join(lines)


def load_registry(path: Path) -> tuple[dict[str, dict[str, Any]], dict[str, dict[str, Any]]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    sections = ("error_codes", "cdc_error_codes")
    if not isinstance(data, dict) or set(data) != set(sections):
        raise SpecError(f"{path}: expected exactly the keys {sections}")
    if any(isinstance(data[s], list) for s in sections):
        raise SpecError(
            f"{path}: a list of codes has no hint, action or side effects; the registry must map each code to "
            '{"hint", "action", "side_effects", "max_retries"}'
        )
    for section in sections:
        for code, info in data[section].items():
            where = f"{path}: {section}.{code}"
            if not re.fullmatch(r"[a-z][a-z0-9_]*", code):
                raise SpecError(f"{where}: a code is snake_case")
            if not isinstance(info, dict) or set(info) != {"hint", "action", "side_effects", "max_retries"}:
                raise SpecError(f"{where}: needs exactly hint, action, side_effects and max_retries")
            if not isinstance(info["hint"], str) or not info["hint"].strip():
                raise SpecError(f"{where}: the hint is empty")
            if info["action"] not in REGISTRY_ACTIONS:
                raise SpecError(f"{where}: action {info['action']!r} is not one of {sorted(REGISTRY_ACTIONS)}")
            if info["side_effects"] not in REGISTRY_SIDE_EFFECTS:
                raise SpecError(
                    f"{where}: side_effects {info['side_effects']!r} is not one of {sorted(REGISTRY_SIDE_EFFECTS)}"
                )
            retries = info["max_retries"]
            if retries is not None and (not isinstance(retries, int) or isinstance(retries, bool) or retries < 0):
                raise SpecError(f"{where}: max_retries is a count or null")
    local = RT.error_catalog.LOCAL_CODES
    clash = sorted(c for c in set(local) & set(data["error_codes"]) if not local[c].server_code)
    if clash:
        raise SpecError(f"client codes {clash} are also server codes; mark them server_code or rename them")
    missing = sorted(c for c, entry in local.items() if entry.server_code and c not in data["error_codes"])
    if missing:
        raise SpecError(f"client codes {missing} are marked server_code but the registry has no such code")
    return data["error_codes"], data["cdc_error_codes"]


def exception_name(code: str) -> str:
    return f"{pascal(code)}Error"


def render_error_codes(server_codes: dict[str, dict[str, Any]]) -> str:
    lines = [
        HEADER.format(doc="Every server error code: its registry entry and its SDK exception."),
        "from databay.errors import DatabayApiError, ErrorInfo",
        "",
        "REGISTRY: dict[str, ErrorInfo] = {",
    ]
    for code, info in sorted(server_codes.items()):
        lines.append(
            f"    {code!r}: ErrorInfo({info['hint']!r}, {info['action']!r}, {info['side_effects']!r}, "
            f"{info['max_retries']!r}),"
        )
    lines += ["}", ""]
    names = set()
    for code in sorted(server_codes):
        name = exception_name(code)
        if name in names:
            raise SpecError(f"{code}: exception name {name} is taken")
        names.add(name)
        lines += ["", f"class {name}(DatabayApiError):", f"    code = {code!r}", ""]
    lines += ["", "EXCEPTIONS: dict[str, type[DatabayApiError]] = {"]
    lines += [f"    {code!r}: {exception_name(code)}," for code in sorted(server_codes)]
    lines += ["}", ""]
    return "\n".join(lines)



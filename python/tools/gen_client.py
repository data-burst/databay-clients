"""
Generate the Python SDK and the ``databay`` CLI from the client contract.

Reads ``contract/core.json`` (the exposed operations), ``contract/error_codes.json`` (the error-code
registry), ``contract/api_version.json`` and the released contract, when there is one
(``contract/core.released.meta.json``, which gives each operation its ``since``), through
``python/tools/contract.py``, and writes under ``python/src/databay/``:

- ``models/<noun>.py`` and ``models/shared.py``: pydantic models, one module per noun, with the
  schemas several nouns use in ``shared``;
- ``operations/<noun>.py``: one ``Operation`` per route, read by the SDK and the CLI;
- ``resources/<noun>.py``: the SDK's resource classes; ``api.py``: one attribute per noun;
- ``cli/commands/<noun>.py``: the CLI's command groups, loaded only when their noun runs;
- ``spec.py`` and ``error_codes.py``: the API version, the noun and operation index, the registry;
- ``version.py``: the package version, from ``python/pyproject.toml``;
- ``skill/references/commands.md`` and ``errors.md``.

    python python/tools/gen_client.py           # write the files
    python python/tools/gen_client.py --check   # exit 1 and list the files that differ

Standard library only. Anything in the spec this generator does not handle is an error naming it.
"""


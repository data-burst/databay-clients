"""
The text of each command's ``--help`` and of the generated ``commands.md`` and ``errors.md``.

``--help`` and the references are rendered by the same functions from the same ``Operation``
data, so they cannot drift. Standard library only: ``python/tools/gen_client.py`` renders the
references with it.
"""

from __future__ import annotations

import inspect
from typing import TYPE_CHECKING, Any

from databay.cli.flags import Flag, command_flags
from databay.error_catalog import EXIT_CODES, LOCAL_CODES, server_exit

if TYPE_CHECKING:
    from collections.abc import Iterable

    from databay.operation import Operation

GENERATED_NOTE = "Generated by python/tools/gen_client.py from contract/core.json; do not edit."


def _description(op: Operation) -> str:
    text = inspect.cleandoc(op.description) if op.description.strip() else ""
    return text or op.summary


def help_paragraphs(op: Operation, variant: str | None = None) -> list[tuple[str, bool]]:
    """``(text, preformatted)`` paragraphs of a command's help; examples keep their lines."""
    paragraphs: list[tuple[str, bool]] = [(part, False) for part in _description(op).split("\n\n") if part.strip()]
    location = op.project_location
    if location is not None:
        where = "the X-Databay-Project-ID header" if location[0] == "header" else f"{location[0]} {location[1]}"
        paragraphs.append((f"Acts in a project, sent as {where}: --project, else the profile's active project.", False))
    if op.destructive:
        paragraphs.append(
            ("Removes or overwrites state: asks on a terminal, and needs --yes when output is captured.", False)
        )
    wait = op.wait or op.resumes
    if wait is not None and not op.offers_wait:
        paragraphs.append(("Answers at once: `next` names the command that waits for it.", False))
    elif wait is not None:
        text = (
            f"--wait polls {wait.status_operation} until {wait.field.lstrip('/')} is "
            f"{' or '.join(wait.success)}; it fails on {', '.join(wait.failure) or 'nothing'}."
        )
        paragraphs.append(
            (
                text,
                False,
            )
        )
    if op.verdict is not None:
        paragraphs.append(
            (f"Exits 9 (not_ready) when {op.verdict.field.lstrip('/')} is {' or '.join(op.verdict.not_ready)}.", False)
        )
    examples = [e for e in op.examples if variant is None or variant in positional_words(e)]
    if examples:
        paragraphs.append(("Examples:\n" + "\n".join(f"  {e}" for e in examples), True))
    return paragraphs


def positional_words(example: str) -> list[str]:
    """The words of an example after ``databay <noun> <verb>`` that are neither a flag nor a flag's value."""
    import shlex  # noqa: PLC0415

    words = shlex.split(example)[3:]
    found: list[str] = []
    index = 0
    while index < len(words):
        word = words[index]
        if not word.startswith("--"):
            found.append(word)
            index += 1
            continue
        following = words[index + 1] if index + 1 < len(words) else None
        index += 1 if following is None or following.startswith("--") else 2
    return found


def click_help(op: Operation, variant: str | None = None) -> str:
    # ``\b`` keeps click from rewrapping a paragraph's lines.
    return "\n\n".join(f"\b\n{text}" if pre else text for text, pre in help_paragraphs(op, variant))


def _usage(op: Operation, flags: list[Flag], variant: str | None) -> str:
    words = [op.command] + ([variant] if variant else [])
    words += [flag.name if flag.required else f"[{flag.name}]" for flag in flags if flag.role == "argument"]
    words.append("[OPTIONS]")
    return " ".join(words)


def _flag_cell(flag: Flag) -> str:
    if flag.takes == "argument":
        return f"`{flag.name}`"
    if flag.takes == "bool":
        return f"`{flag.name}` / `--no-{flag.name.removeprefix('--')}`"
    if flag.takes == "switch":
        return f"`{flag.name}`"
    metavar = flag.metavar or (flag.param.kind.upper() if flag.param else "TEXT")
    suffix = " (repeat)" if flag.takes == "multiple" else ""
    return f"`{flag.name} {metavar}`{suffix}"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _command_section(op: Operation, variant: str | None) -> list[str]:
    title = f"{op.command} {variant}" if variant else op.command
    lines = [f"### {title}", ""]
    for text, pre in help_paragraphs(op, variant):
        lines += (["```", text, "```"] if pre else [text]) + [""]
    flags = command_flags(op, variant)
    lines += [f"Usage: `{_usage(op, flags, variant)}`", "", "| Argument or flag | Required | Description |"]
    lines.append("|---|---|---|")
    for flag in flags:
        text = flag.help
        if flag.choices:
            text = (f"{text.rstrip('.')}. " if text else "") + f"One of: {', '.join(flag.choices)}."
        required = "yes" if flag.required else ""
        lines.append(f"| {_flag_cell(flag)} | {required} | {_cell(text)} |")
    lines.append("")
    return lines


def commands_markdown(
    operations: Iterable[Operation], curated: dict[str, str], handwritten: dict[str, tuple[str, str, str]]
) -> str:
    """
    ``commands.md``: every generated command, the operations a hand-written command replaces, then those commands.

    ``curated`` maps an operation id to the hand-written command that replaces it; ``handwritten``
    holds the hand-written commands this CLI has, so one it lacks is listed as not available.
    """
    available = set(handwritten)
    by_noun: dict[str, list[Operation]] = {}
    for op in operations:
        by_noun.setdefault(op.noun, []).append(op)
    lines = ["# databay commands", "", GENERATED_NOTE, ""]
    lines += ["Every command also takes the flags `--output`, `--profile`, `--verbose` and `--no-retry`.", ""]
    replaced: list[tuple[Operation, str]] = []
    for noun in sorted(by_noun):
        generated = [op for op in sorted(by_noun[noun], key=lambda o: o.verb) if op.operation_id not in curated]
        replaced += [(op, curated[op.operation_id]) for op in by_noun[noun] if op.operation_id in curated]
        if not generated:
            continue
        lines += [f"## {noun}", ""]
        for op in generated:
            if op.body is not None and op.body.discriminator is not None:
                for key, _, _ in op.body.variants:
                    lines += _command_section(op, key)
            else:
                lines += _command_section(op, None)
    if replaced:
        lines += ["## Operations with a hand-written command", "", "| Operation | Command |", "|---|---|"]
        for op, command in replaced:
            status = "" if command.split()[0] in available else " (not in this CLI version)"
            lines.append(f"| `{op.method.upper()} {op.path}` | `databay {command}`{status} |")
        lines.append("")
    lines += ["## Hand-written commands", "", "`databay <command> --help` lists the flags of each.", ""]
    lines += ["| Command | What it does |", "|---|---|"]
    lines += [f"| `databay {name}` | {_cell(entry[2])} |" for name, entry in sorted(handwritten.items())]
    lines.append("")
    return "\n".join(lines)


def errors_markdown(server_codes: dict[str, dict[str, Any]], pipe_codes: dict[str, dict[str, Any]]) -> str:
    """``errors.md``: the exit codes, the client's own codes, the server's codes and the pipe failure codes."""
    lines = ["# databay errors", "", GENERATED_NOTE, ""]
    lines += [
        "When output is captured, a failed command prints one JSON object on stderr:",
        '`{"error": {"code", "message", "hint", "next", "recovery", "context", ...}}`.',
        "Read `recovery.action` first; the exit code is the coarse class.",
        "",
        "## Exit codes",
        "",
        "| Exit | Meaning |",
        "|---|---|",
    ]
    lines += [f"| {code} | {_cell(text)} |" for code, text in EXIT_CODES.items()]
    lines += ["", "## Client codes", "", "| Code | Exit | Action | Side effects | Hint |", "|---|---|---|---|---|"]
    for code, local in sorted(LOCAL_CODES.items()):
        hint = server_codes[code]["hint"] if local.server_code else local.hint
        lines.append(f"| `{code}` | {local.exit_code} | {local.action} | {local.side_effects} | {_cell(hint)} |")
    lines += [
        "",
        "## Server codes",
        "",
        "| Code | Exit | Action | Side effects | Max retries | Hint |",
        "|---|---|---|---|---|---|",
    ]
    for code, info in sorted(server_codes.items()):
        exit_code = LOCAL_CODES[code].exit_code if code in LOCAL_CODES else server_exit(code, info["action"])
        lines.append(
            f"| `{code}` | {exit_code} | {info['action']} | {info['side_effects']} | {_retries(info['max_retries'])} "
            f"| {_cell(info['hint'])} |"
        )
    lines += [
        "",
        "## Pipe failure codes",
        "",
        "A pipe that fails records one of these in `error_code`; a wait that ends on the failure reports it.",
        "",
        "| Code | Action | Side effects | Max retries | Hint |",
        "|---|---|---|---|---|",
    ]
    for code, info in sorted(pipe_codes.items()):
        retries = _retries(info["max_retries"])
        lines.append(f"| `{code}` | {info['action']} | {info['side_effects']} | {retries} | {_cell(info['hint'])} |")
    lines.append("")
    return "\n".join(lines)


def _retries(value: int | None) -> str:
    return "" if value is None else str(value)
